void main() {
  int a = 10;
  int b = 3;
  int c = a + b;
  print("The result of a+b is = $c");

  int d = a - b;
  print("The result of a-b is = $d");

  int e = a * b;
  print("The result of a*b is = $e");

  num f = a / b;
  print("The division of a/b is = $f");

  int g = a % b;
  print("The mod of a % b is = $g");
}
